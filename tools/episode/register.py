#!/usr/bin/env python3
"""Register every episode with Remotion: writes packages/animator/src/episodes/registry.ts,
which Root.tsx turns into compositions Ep001, Ep002, ... An episode is registered once
it has both beats.json and audio/timing.json. build.py runs this before rendering.

Usage:
  python tools/episode/register.py
Standard library only.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ANIM, EPISODES  # noqa: E402

OUT = ANIM / "src" / "episodes" / "registry.ts"


def episodes():
    for d in sorted(EPISODES.iterdir()):
        if d.is_dir() and d.name.isdigit() and (d / "beats.json").exists() and (d / "audio" / "timing.json").exists():
            yield int(d.name), d.name


def render():
    eps = list(episodes())
    imports = "".join(f"import beats{name} from '../../../../episodes/{name}/beats.json';\n"
                      f"import timing{name} from '../../../../episodes/{name}/audio/timing.json';\n" for _, name in eps)
    rows = "".join(f"  {{n: {n}, beats: beats{name}, timing: timing{name}}},\n" for n, name in eps)
    return ("// Generated by tools/episode/register.py from the episodes/ folders. Do not edit by hand.\n"
            f"{imports}\n"
            "export type EpisodeEntry = {n: number; beats: unknown; timing: unknown};\n\n"
            f"export const EPISODES: EpisodeEntry[] = [\n{rows}];\n")


def main():
    text = render()
    names = ", ".join(f"Ep{name}" for _, name in episodes())
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"registered {names} in {OUT.relative_to(ANIM)}")
    else:
        print(f"episode registry up to date ({names})")


if __name__ == "__main__":
    main()
